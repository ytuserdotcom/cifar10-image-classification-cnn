# Number of training epochs
epochs = 25

# Store training and validation results
train_losses = []
val_losses = []

train_accuracies = []
val_accuracies = []

# Best validation accuracy
best_accuracy = 0.0


for epoch in range(epochs):

    # ---------------- TRAINING ----------------

    model.train()

    running_loss = 0.0
    correct = 0
    total = 0

    for images, labels in train_loader:

        # Move data to GPU or CPU
        images = images.to(device)
        labels = labels.to(device)

        # Clear previous gradients
        optimizer.zero_grad()

        # Forward propagation
        outputs = model(images)

        # Calculate loss
        loss = criterion(outputs, labels)

        # Backward propagation
        loss.backward()

        # Update model weights
        optimizer.step()

        # Calculate total loss
        running_loss += loss.item()

        # Get predicted class
        _, predicted = torch.max(outputs.data, 1)

        total += labels.size(0)
        correct += (predicted == labels).sum().item()

    # Calculate training loss and accuracy
    epoch_train_loss = running_loss / len(train_loader)
    epoch_train_acc = 100 * correct / total

    train_losses.append(epoch_train_loss)
    train_accuracies.append(epoch_train_acc)


    # ---------------- VALIDATION ----------------

    model.eval()

    val_loss = 0.0
    val_correct = 0
    val_total = 0

    # No gradient calculation during validation
    with torch.no_grad():

        for images, labels in val_loader:

            images = images.to(device)
            labels = labels.to(device)

            outputs = model(images)

            loss = criterion(outputs, labels)

            val_loss += loss.item()

            _, predicted = torch.max(outputs.data, 1)

            val_total += labels.size(0)
            val_correct += (predicted == labels).sum().item()

    # Calculate validation results
    epoch_val_loss = val_loss / len(val_loader)
    epoch_val_acc = 100 * val_correct / val_total

    val_losses.append(epoch_val_loss)
    val_accuracies.append(epoch_val_acc)


    # Save best model
    if epoch_val_acc > best_accuracy:

        best_accuracy = epoch_val_acc

        torch.save(
            model.state_dict(),
            "best_cifar10_model.pth"
        )


    # Display epoch results
    print(f"Epoch [{epoch+1}/{epochs}]")
    print(f"Train Loss: {epoch_train_loss:.4f}")
    print(f"Train Accuracy: {epoch_train_acc:.2f}%")
    print(f"Validation Loss: {epoch_val_loss:.4f}")
    print(f"Validation Accuracy: {epoch_val_acc:.2f}%")
    print("-" * 45)


