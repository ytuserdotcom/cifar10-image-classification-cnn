    # Model prediction
    with torch.no_grad():

        outputs = model(image_tensor)

        # Convert logits into probabilities
        probabilities = torch.softmax(outputs, dim=1)

        # Get predicted class
        confidence, predicted_class = torch.max(
            probabilities, dim=1
        )

    # Predicted class name
    predicted_name = classes[predicted_class.item()]

    # Confidence percentage
    confidence_value = confidence.item() * 100

    # All 10 confidence scores
    scores = {
        classes[i]: float(probabilities[0][i].item())
        for i in range(10)
    }

    # Create DataFrame for bar chart
    chart_data = pd.DataFrame({
        "Class": classes,
        "Confidence": [
            probabilities[0][i].item() * 100
            for i in range(10)
        ]
    })

    # Sort confidence from highest to lowest
    chart_data = chart_data.sort_values(
        by="Confidence",
        ascending=False
    )

    # Prediction result
    result = f"{predicted_name} ({confidence_value:.2f}%)"

    return original_image, result, scores, chart_data

